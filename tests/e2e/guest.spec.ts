test('responsive viewports avoid horizontal scroll and reduced motion disables parallax', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [360, 390, 430, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByLabel('Nama produk')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(await page.evaluate(() => Array.from(document.querySelectorAll('.qk-invoice-sheet')).every((element) => getComputedStyle(element).transform === 'none'))).toBe(true)
  }
  await page.setViewportSize(testInfo.project.name === 'mobile' ? { width: 390, height: 844 } : { width: 1440, height: 1100 })
  await page.goto('/')
  await page.screenshot({ path: `test-results/quotekilat-${testInfo.project.name}.png`, fullPage: true, animations: 'disabled' })
  await expect(page.getByRole('button', { name: 'Unduh PDF' })).toBeEnabled()
})
