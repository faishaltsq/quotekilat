test('draft survives reload and legal navigation, personal data requires opt-in, clear does not resurrect', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Nama produk').fill('Produk uji lokal')
  await page.getByText('Detail penawaran', { exact: false }).click()
  await page.getByLabel('Nama pelanggan', { exact: true }).fill('Data pribadi uji')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('quotekilat:guest-draft:v1'))).not.toContain('Data pribadi uji')
  await page.getByRole('link', { name: 'Privasi', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText(/privasi/i)
  await page.getByRole('link', { name: 'QuoteKilat beranda' }).click()
  await expect(page.getByLabel('Nama produk')).toHaveValue('Produk uji lokal')
  await page.getByText('Detail penawaran', { exact: false }).click()
  await expect(page.getByLabel('Nama pelanggan', { exact: true })).toHaveValue('Data pribadi uji')
  await page.reload()
  await page.getByText('Detail penawaran', { exact: false }).click()
  await expect(page.getByLabel('Nama pelanggan', { exact: true })).toHaveValue('')
  await page.getByLabel('Nama pelanggan', { exact: true }).fill('Diizinkan lokal')
  await page.getByRole('checkbox').check()
  await page.reload()
  await page.getByText('Detail penawaran', { exact: false }).click()
  await expect(page.getByLabel('Nama pelanggan', { exact: true })).toHaveValue('Diizinkan lokal')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Hapus data perangkat' }).click()
  await expect(page.getByLabel('Nama produk')).toHaveValue('')
  expect(await page.evaluate(() => localStorage.getItem('quotekilat:guest-draft:v1'))).toBeNull()
  await page.reload()
  expect(await page.evaluate(() => localStorage.getItem('quotekilat:guest-draft:v1'))).toBeNull()
})

